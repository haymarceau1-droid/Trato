const toBrands = (type: VehicleType, data: Record<string, string[]>): CatalogBrand[] =>
  Object.entries(data)
    .map(([name, models]) => ({
      name,
      slug: slugify(name),
      vehicle_type: type,
      models: [...new Set(models)]
        .map((m) => ({ name: m, slug: slugify(m) }))
        .sort((a, b) => a.name.localeCompare(b.name, "es", { numeric: true })),
    }))
    .sort((a, b) => a.name.localeCompare(b.name, "es"));

const CATALOG: Record<VehicleType, CatalogBrand[]> = {
  auto: toBrands("auto", AUTOS),
  moto: toBrands("moto", MOTOS),
};

export const getCatalog = (type: VehicleType): CatalogBrand[] => CATALOG[type];

